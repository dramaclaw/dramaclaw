/**
 * 落地：把一个对象放到它正下方那个表面上。
 *
 * 预演台里有两处要落地——手柄松手时的一次性吸附，和「贴地」策略的人物每帧跟随地形。
 * 两处都得先朝下打一条射线拿到表面高度，再把对象挪到那个高度上。这里装的就是这两步
 * 里不碰 three 的那一半：射线从多高起、拿到表面之后 y 该变成多少。
 *
 * 把它抠成一个模块，是因为「两套落地各自算高度」是一类特别难查的 bug：两边只要有一处
 * 写成直接赋值、或者射线起点抬得不一样，绝大多数对象上看不出区别，只有某一个原点不在
 * 脚底的道具会在拖完之后自己沉下去半截，或者在切到贴地策略的那一帧跳一下。共用同一个
 * 常量和同一个公式，这种漂移就没有地方产生。
 *
 * 这里刻意不认「对象」也不认场景：入参只有三个数。包围盒要由 three 在渲染器里算
 * （`Box3.setFromObject`，得有真实的几何），而渲染器在测试里是被打桩的——真正容易
 * 写错的偏移方向和退化输入如果留在渲染器里，就只能靠肉眼在浏览器里看。
 */

/**
 * 射线起点相对包围盒顶面的抬高，单位米。
 *
 * 不抬的话有一类必挂的场景：对象已经严丝合缝坐在表面上，此时起点与命中面共面，
 * 射线要么判为零距离要么直接漏掉，落地表现为「第一次拖动之后再吸附一次就掉到地板」。
 *
 * 1 mm 是两头夹出来的：要比几何求交的浮点误差大得多才挡得住共面，又要远小于场景里
 * 任何看得见的量（网格一格是米级），这样抬高本身不会变成一个可见的偏差。
 */
export const PREVIZ_DROP_EPSILON = 1e-3;

/**
 * 朝下探测表面的射线该从多高发出：包围盒顶面再抬一点点。
 *
 * 从顶面而不是从底面起射，是为了让对象**当前**就压着的那个面也能被命中——从底面起射
 * 会把脚下的桌面漏在射线背后，对象于是穿过桌子掉到地板上。
 *
 * 空包围盒的 `max.y` 是 -Infinity，这里原样传出去而不兜成 0：调用方看到非有限值就该
 * 整个跳过这次落地，而 `dropPositionY` 对同一个盒子恰好也是空操作，两边判断一致。
 */
export function dropRayOriginY(boxMaxY: number): number {
  return boxMaxY + PREVIZ_DROP_EPSILON;
}

/**
 * 把包围盒底面贴到 `surfaceY` 上之后，对象的 y 该是多少。
 *
 * 算的是**位移**（`currentY + (surfaceY - boxMinY)`）而不是直接 `y = surfaceY`：
 * 对象原点不保证在脚底。导入的 obj 模型原点常在几何中心，直接赋值会把它一半埋进地里；
 * 原点在头顶的模型则会整个浮到空中。位移只依赖「底面离原点多远」，与原点在哪无关。
 *
 * 包围盒或表面非有限就原样返回 `currentY`：空包围盒的 `min.y` 是 +Infinity，射线没
 * 命中时表面高度也可能是 Infinity，两者减出来都是 NaN。让 NaN 落进 transform 的代价是
 * 对象从画面上彻底消失（three 会把 NaN 矩阵整条渲染管线传下去），而且再也拖不回来——
 * 宁可这一次不动。兜底只兜成「不动」而不是「归零」：坏帧上跳回原点同样是丢位置。
 *
 * `currentY` 自己不用判：它非有限时加上一个有限位移仍然是同一个非有限值，再写一个
 * 分支只是一段永远不会改变结果的死代码。
 */
export function dropPositionY(currentY: number, boxMinY: number, surfaceY: number): number {
  if (!Number.isFinite(boxMinY) || !Number.isFinite(surfaceY)) return currentY;
  return currentY + (surfaceY - boxMinY);
}
